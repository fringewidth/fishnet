"""Parse PeSTO tables from two independent sources, check they agree, emit tables.h.

Also emits 32-bit Zobrist keys from a fixed-seed xorshift so both builds share them.
Square convention in the output: sq64 = rank*8 + file, a1 = 0 (white's view).
PeSTO source tables are laid out a8 first (index (7-rank)*8 + file for white).
"""
import re
import sys

NAMES = ["pawn", "knight", "bishop", "rook", "queen", "king"]


def parse(path):
    src = open(path).read()
    out = {}
    for ph in ("mg", "eg"):
        m = re.search(ph + r"_value\[6\]\s*=\s*\{([^}]*)\}", src)
        out[ph + "_value"] = [int(x) for x in re.findall(r"-?\d+", m.group(1))]
        for n in NAMES:
            m = re.search(rf"{ph}_{n}_table\[64\]\s*=\s*\{{([^}}]*)\}}", src)
            vals = [int(x) for x in re.findall(r"-?\d+", m.group(1))]
            assert len(vals) == 64, (path, ph, n, len(vals))
            out[f"{ph}_{n}"] = vals
    return out


def main():
    a, b = parse(sys.argv[1]), parse(sys.argv[2])
    diff = [k for k in a if a[k] != b[k]]
    if diff:
        sys.exit(f"sources disagree on: {diff}")
    lines = ["/* Generated by tools/gen_tables.py. PeSTO (Ronald Friederich) material + PST,",
             "   white's view, sq64 = rank*8 + file (a1 = 0). Black uses sq64 ^ 56. */",
             "#pragma once", "#include <stdint.h>", ""]
    for ph in ("mg", "eg"):
        lines.append(f"static const int16_t PST_{ph.upper()}[6][64] = {{")
        for p, n in enumerate(NAMES):
            vals = []
            for sq in range(64):
                r, f = divmod(sq, 8)
                vals.append(a[f"{ph}_value"][p] + a[f"{ph}_{n}"][(7 - r) * 8 + f])
            lines.append("  {" + ",".join(map(str, vals)) + "},")
        lines.append("};")
    x = 0x9E3779B9
    def rnd():
        nonlocal x
        x ^= (x << 13) & 0xFFFFFFFF
        x ^= x >> 17
        x ^= (x << 5) & 0xFFFFFFFF
        return x
    keys = [[rnd() for _ in range(64)] for _ in range(12)]
    lines.append("static const uint32_t ZOB_PIECE[12][64] = {")
    for row in keys:
        lines.append("  {" + ",".join(f"0x{k:08x}u" for k in row) + "},")
    lines.append("};")
    lines.append("static const uint32_t ZOB_CASTLE[16] = {" + ",".join(f"0x{rnd():08x}u" for _ in range(16)) + "};")
    lines.append("static const uint32_t ZOB_EP[8] = {" + ",".join(f"0x{rnd():08x}u" for _ in range(8)) + "};")
    lines.append(f"static const uint32_t ZOB_SIDE = 0x{rnd():08x}u;")
    # ALIGN[to - from + 119] != 0 when two 0x88 squares share a rank, file or diagonal
    align = [0] * 239
    for d in (1, 15, 16, 17):
        for k in range(1, 8):
            align[119 + d * k] = 1
            align[119 - d * k] = 1
    lines.append("static const uint8_t ALIGN[239] = {" + ",".join(map(str, align)) + "};")
    open(sys.argv[3], "w").write("\n".join(lines) + "\n")
    print("ok: sources agree;", sys.argv[3])


main()
